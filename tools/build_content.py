"""Authoring source for PyLearn's course content.

Run:  python3 tools/build_content.py   ->  writes content/course.json
Then: python3 tools/verify_content.py  ->  runs every example and answer with python3

The site itself only reads content/course.json, so no build step is needed to host it.
"""
import json, os

def card(title, text, code=None, out=None, stdin=None, error=None, note=None):
    s = {"type": "card", "title": title, "text": text}
    if code is not None: s["code"] = code.strip("\n")
    if out is not None: s["out"] = out
    if stdin: s["stdin"] = stdin
    if error: s["error"] = error
    if note: s["note"] = note
    return s

def mcq(q, options, answer, explain, hint, code=None, error=None, mono=False):
    s = {"type": "mcq", "q": q, "options": options, "answer": answer, "explain": explain, "hint": hint, "mono": mono}
    if code is not None: s["code"] = code.strip("\n")
    if error: s["error"] = error
    return s

def output(code, options, answer, explain, hint, stdin=None):
    s = {"type": "output", "q": "What does this print?", "code": code.strip("\n"), "options": options,
         "answer": answer, "explain": explain, "hint": hint, "mono": True}
    if stdin: s["stdin"] = stdin
    return s

def fill(q, code, answers, distractors, expect, explain, hint, stdin=None):
    s = {"type": "fill", "q": q, "code": code.strip("\n"), "answers": answers, "distractors": distractors,
         "expect": expect, "explain": explain, "hint": hint}
    if stdin: s["stdin"] = stdin
    return s

def order(q, lines, expect, explain, hint, stdin=None):
    s = {"type": "order", "q": q, "lines": lines, "expect": expect, "explain": explain, "hint": hint}
    if stdin: s["stdin"] = stdin
    return s

def challenge(q, starter, tests, solution, hint, explain, require=None):
    s = {"type": "code", "q": q, "starter": starter, "tests": tests, "solution": solution.strip("\n"),
         "hint": hint, "explain": explain}
    if require: s["require"] = require
    return s

def T(expected, stdin=None, after=None):
    t = {"expected": expected}
    if stdin: t["stdin"] = stdin
    if after: t["after"] = after
    return t

